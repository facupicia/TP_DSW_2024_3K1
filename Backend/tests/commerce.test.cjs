test('release migration restores durable columns removed by legacy schema synchronization', async () => {
  const db = await database();
  try {
    await db.exec(`ALTER TABLE account_claim_token ADD COLUMN "usedAt" timestamptz;
      CREATE TABLE refresh_token(id integer PRIMARY KEY,"revokedAt" timestamptz);
      INSERT INTO refresh_token VALUES(1,NULL);
      INSERT INTO account_claim_token(id,purpose,"credentialsVersion") VALUES(2,'reset',3);
      ALTER TABLE "user" DROP COLUMN "credentialsVersion";
      ALTER TABLE account_claim_token DROP COLUMN purpose, DROP COLUMN "credentialsVersion";
      ALTER TABLE event DROP COLUMN "timeZone";`);
    const { RestoreDurableColumns1794919800000 } = load('database/migrations/20261117125000-restore-durable-columns.ts');
    const repair = new RestoreDurableColumns1794919800000();
    await repair.up({ query: queryAdapter(db) });
    assert.ok((await db.query('SELECT "credentialsVersion" FROM "user" WHERE id=3')).rows[0].credentialsVersion > 0);
    assert.ok((await db.query('SELECT "revokedAt" FROM refresh_token WHERE id=1')).rows[0].revokedAt);
    assert.ok((await db.query('SELECT "usedAt" FROM account_claim_token WHERE id=2')).rows[0].usedAt);
    assert.equal((await db.query('SELECT "timeZone" FROM event WHERE id=1')).rows[0].timeZone, 'America/Argentina/Buenos_Aires');
    await db.exec(`UPDATE "user" SET "credentialsVersion"=7 WHERE id=3;
      INSERT INTO account_claim_token(id,purpose,"credentialsVersion") VALUES(1,'reset',7);`);
    await repair.up({ query: queryAdapter(db) });
    assert.equal((await db.query('SELECT "credentialsVersion" FROM "user" WHERE id=3')).rows[0].credentialsVersion, 7);
    assert.equal((await db.query('SELECT purpose FROM account_claim_token WHERE id=1')).rows[0].purpose, 'reset');
    assert.equal((await db.query('SELECT "usedAt" FROM account_claim_token WHERE id=1')).rows[0].usedAt, null);
  } finally { await db.close(); }
});

